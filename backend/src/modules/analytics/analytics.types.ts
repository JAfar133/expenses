import type { ExcelState } from '../../storage/excel-state.ts';
import type { ExpenseScope } from '../groups/scope.ts';

/** Common filters of the analytics page. An empty list means "no restriction". */
export interface AnalyticsFilters {
  /** Period bounds, inclusive, YYYY-MM-DD */
  from?: string;
  to?: string;
  cards: string[];
  categories: string[];
  /** Logins of the users who added the expense */
  createdBy: string[];
  /** Expense entry currency; a dram expense is the base currency */
  currencies: string[];
  /** Part of the name, case-insensitive */
  q?: string;
  minAmount?: number;
  maxAmount?: number;
  /** "Everything except": values to leave out (the user crossed them out in the filter) */
  excludeCards?: string[];
  excludeCategories?: string[];
  excludeCreatedBy?: string[];
  excludeCurrencies?: string[];
  includeDeleted: boolean;
  /**
   * Leave out expenses of archived cards and categories (unless that card or category is chosen in the filter).
   * Set by the routes; not set (internal use, limits) means everything counts.
   */
  excludeArchived?: boolean;
  /**
   * What the user may see (group and cards). Set by the routes from the logged-in user, never from the query;
   * without it the query is not limited (internal use and tests).
   */
  scope?: ExpenseScope;
  /**
   * The currency the amounts are summed in. A record entered (or kept) in that currency counts with its exact amount,
   * the others are converted from drams at the rate of their day. Without it: the group's reporting currency.
   */
  display?: { currency: string; rate: number };
}

export interface SummaryStats {
  total: number;
  count: number;
  average: number;
  median: number;
  max: number;
  /** How many distinct days have expenses */
  activeDays: number;
  firstDate: string | null;
  lastDate: string | null;
}

export const BREAKDOWN_DIMENSIONS = [
  'category',
  'card',
  'name',
  'weekday',
  'currency',
  'createdBy',
] as const;
export type BreakdownBy = (typeof BREAKDOWN_DIMENSIONS)[number];

export interface BreakdownRow {
  /** Group value; for the day of week the number 1 (Monday) … 7 (Sunday) */
  key: string;
  total: number;
  count: number;
  average: number;
}

export const GRANULARITIES = ['day', 'week', 'month'] as const;
export type Granularity = (typeof GRANULARITIES)[number];

export const SERIES_SPLITS = ['category', 'card'] as const;
export type SeriesSplit = (typeof SERIES_SPLITS)[number];

export interface SeriesPoint {
  /** First day of the period, YYYY-MM-DD */
  period: string;
  /** Breakdown value (category or card); absent if there is no breakdown */
  key?: string;
  total: number;
  count: number;
}

export const SORT_COLUMNS = ['date', 'card', 'category', 'name', 'amount', 'createdBy'] as const;
export type SortColumn = (typeof SORT_COLUMNS)[number];
export type SortDirection = 'asc' | 'desc';

export interface ListOptions {
  sort: SortColumn;
  direction: SortDirection;
  limit: number;
  offset: number;
}

export interface ExpenseListItem {
  id: string;
  date: string;
  card: string;
  category: string;
  name: string;
  /** Amount in the currency of the card */
  amount: number;
  /** Currency of the card (and of `amount`) */
  currency: string;
  /** When the record was created (ISO) */
  createdAt: string;
  /**
   * The user of the request may correct or delete this record: the owner any one, a member their own within the time
   * the owner allows (set by the route for the logged-in user)
   */
  editable?: boolean;
  /** Until when a member may still correct their record (ISO); only for members */
  editableUntil?: string | null;
  /** The amount in whole drams: the first five columns of the old Excel table */
  dramsAmount: number;
  /** The same amount in the currency of the request (`?currency=`; the reporting currency without it) */
  displayAmount: number;
  /** The same amount in the group's reporting currency */
  reportingAmount: number;
  reportingCurrency: string;
  original: { amount: number; currency: string; rate: number } | null;
  createdBy: string;
  source: 'app' | 'excel';
  excelStatus: 'pending' | 'writing' | 'synced';
  /** How the record relates to the Excel row: identical, waiting for a write, update or removal */
  excelState: ExcelState;
  /** Reason for the delay of the Excel write (the last error), if there was one */
  excelError: string | null;
  deletedAt: string | null;
  deletedReason: 'excel' | 'app' | null;
  updatedBy: string | null;
  /** A receipt photo is attached */
  hasReceipt: boolean;
  /** Positions of the receipt and how many of them the AI generated */
  itemsCount: number;
  aiItemsCount: number;
  /** Where the name and the date came from: `ai` is shown with the "generated by AI" mark */
  nameSource: 'default' | 'manual' | 'ai';
  dateSource: 'default' | 'manual' | 'ai';
  /** The receipt was parsed by the AI (also after a person fixed everything) */
  aiProcessed: boolean;
}

/** Who added expenses: login for the filter and name for display. */
export interface Author {
  value: string;
  label: string;
  count: number;
}

export interface ExpenseListPage {
  items: ExpenseListItem[];
  /** Total records matching the filters (for paging) and their sum */
  total: number;
  totalAmount: number;
}
