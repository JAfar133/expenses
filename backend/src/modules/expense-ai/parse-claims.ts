import type { SqlExecutor } from '../../infrastructure/database/database.ts';
import type { LlmRepository } from '../llm/llm.repository.ts';
import type { ReceiptDraft } from './receipt-draft.service.ts';

/** What a new expense takes from a receipt parsed earlier: which of its values really are the AI's. */
export interface ClaimedParse {
  model: string;
  nameIsAi: boolean;
  dateIsAi: boolean;
  /** For each item of the expense: is it one of the parsed items, unchanged */
  itemIsAi: boolean[];
}

interface NewExpenseValues {
  name: string;
  date: string;
  items: { name: string; price: number; quantity: number }[];
}

/**
 * A receipt can be parsed while the form is still open. When the expense is saved, the server compares what was saved
 * with what the model said: a value counts as generated by the AI only if it is exactly the model's value.
 * So the marks cannot be forged, and a value the person changed is theirs.
 */
export class ParseClaims {
  constructor(private readonly repository: Pick<LlmRepository, 'claim'>) {}

  async claim(
    db: SqlExecutor,
    claim: { usageId: string; groupId: string; username: string; expenseId: string },
    values: NewExpenseValues,
  ): Promise<ClaimedParse | undefined> {
    const taken = await this.repository.claim(db, claim);
    if (!taken) return undefined;
    const draft = taken.result as Partial<ReceiptDraft>;

    // Every parsed item may be matched once, so two equal lines do not both match one parsed line
    const available = [...(draft.items ?? [])];
    const itemIsAi = values.items.map((item) => {
      const index = available.findIndex(
        (parsed) =>
          parsed.name === item.name &&
          parsed.price === item.price &&
          parsed.quantity === item.quantity,
      );
      if (index < 0) return false;
      available.splice(index, 1);
      return true;
    });
    return {
      model: taken.model,
      nameIsAi: draft.name != null && draft.name === values.name,
      dateIsAi: draft.date != null && draft.date === values.date,
      itemIsAi,
    };
  }
}
